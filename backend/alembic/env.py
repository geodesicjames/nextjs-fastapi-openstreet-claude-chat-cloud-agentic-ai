"""Alembic migration environment.

Compared with Django migrations:
- Alembic does not discover models by itself; `target_metadata` below points it
  at our `Base.metadata`, and `alembic revision --autogenerate -m "..."` diffs
  that metadata against the live database.
- Autogenerated migrations are a draft: always read and edit them before
  committing (renames, data migrations and PostGIS details need a human).

The database URL comes from app settings (DATABASE_URL), not alembic.ini, so
there is a single source of truth for configuration.
"""

import asyncio
from logging.config import fileConfig

from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.sql.schema import SchemaItem

from alembic import context
from app.config import get_settings
from app.models import Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata

DATABASE_URL = str(get_settings().database_url)

# Tables owned by PostGIS rather than by us. Without this, autogenerate would
# see them in the database but not in our models and propose dropping them.
POSTGIS_TABLES = {"spatial_ref_sys"}


def include_object(
    obj: SchemaItem,
    name: str | None,
    type_: str,
    reflected: bool,
    compare_to: SchemaItem | None,
) -> bool:
    return not (type_ == "table" and name in POSTGIS_TABLES)


def run_migrations_offline() -> None:
    """Emit SQL to stdout instead of running it (`alembic upgrade head --sql`)."""
    context.configure(
        url=DATABASE_URL,
        target_metadata=target_metadata,
        include_object=include_object,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        include_object=include_object,
    )

    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    # Alembic's migration API is synchronous; `run_sync` bridges our async
    # engine to it.
    engine = create_async_engine(DATABASE_URL, poolclass=pool.NullPool)

    async with engine.connect() as connection:
        await connection.run_sync(do_run_migrations)

    await engine.dispose()


def run_migrations_online() -> None:
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
