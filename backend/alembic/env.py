"""Alembic migration environment.

Compared with Django migrations:
- Alembic does not discover models by itself; `target_metadata` below points it
  at our `Base.metadata`, and `alembic revision --autogenerate -m "..."` diffs
  that metadata against the live database.
- Autogenerated migrations are a draft: always read and edit them before
  committing (renames, data migrations and PostGIS details need a human).

The database URL comes from app settings (DATABASE_URL), not alembic.ini, so
there is a single source of truth for configuration.
"""

import asyncio
from logging.config import fileConfig

from geoalchemy2 import alembic_helpers
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.sql.schema import SchemaItem

from alembic import context
from app.config import get_settings
from app.models import Base

config = context.config

if config.config_file_name is not None:
    # disable_existing_loggers=False: the default silences every logger that
    # already exists, e.g. the app's own when the test suite runs migrations.
    fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = Base.metadata

DATABASE_URL = str(get_settings().database_url)

# Tables owned by PostGIS rather than by us. Without this, autogenerate would
# see them in the database but not in our models and propose dropping them.
POSTGIS_TABLES = {"spatial_ref_sys"}


def include_object(
    obj: SchemaItem,
    name: str | None,
    type_: str,
    reflected: bool,
    compare_to: SchemaItem | None,
) -> bool:
    if type_ == "table" and name in POSTGIS_TABLES:
        return False
    # GeoAlchemy2's filter skips the spatial indexes it manages itself.
    return alembic_helpers.include_object(obj, name, type_, reflected, compare_to)


# GeoAlchemy2 helpers so autogenerate renders Geometry columns and creates
# their spatial (GiST) indexes correctly.
GEO_OPTIONS = {
    "process_revision_directives": alembic_helpers.writer,
    "render_item": alembic_helpers.render_item,
}


def run_migrations_offline() -> None:
    """Emit SQL to stdout instead of running it (`alembic upgrade head --sql`)."""
    context.configure(
        url=DATABASE_URL,
        target_metadata=target_metadata,
        include_object=include_object,
        **GEO_OPTIONS,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        include_object=include_object,
        **GEO_OPTIONS,
    )

    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    # Alembic's migration API is synchronous; `run_sync` bridges our async
    # engine to it.
    #
    # search_path=public: the postgis/postgis image adds its `tiger` and
    # `topology` schemas to the default search path, which makes their ~36
    # tables look like ours to autogenerate (and it proposes dropping them).
    # PostGIS itself and all our tables live in `public`.
    engine = create_async_engine(
        DATABASE_URL,
        poolclass=pool.NullPool,
        connect_args={"server_settings": {"search_path": "public"}},
    )

    async with engine.connect() as connection:
        await connection.run_sync(do_run_migrations)

    await engine.dispose()


def run_migrations_online() -> None:
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
